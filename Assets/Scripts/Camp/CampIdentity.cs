using System;
using System.IO;
using System.Security.Cryptography;
using System.Text;
using UnityEngine;
namespace CyberExtraction.Camp
{
    [Serializable] public class CampKey
    {
        public string Modulus, Exponent, D, P, Q, DP, DQ, InverseQ;
        static string E(byte[] b)=>b==null ? null : Convert.ToBase64String(b);
        static byte[] B(string s)=>string.IsNullOrEmpty(s) ? null : Convert.FromBase64String(s);
        public static CampKey From(RSAParameters p)=>new CampKey { Modulus=E(p.Modulus),Exponent=E(p.Exponent),D=E(p.D),P=E(p.P),Q=E(p.Q),DP=E(p.DP),DQ=E(p.DQ),InverseQ=E(p.InverseQ) };
        public RSAParameters Parameters()=>new RSAParameters { Modulus=B(Modulus),Exponent=B(Exponent),D=B(D),P=B(P),Q=B(Q),DP=B(DP),DQ=B(DQ),InverseQ=B(InverseQ) };
        public string Public=>Modulus+":"+Exponent;
        public string Session { get { using(var sha=SHA256.Create()) { var hash=sha.ComputeHash(Encoding.UTF8.GetBytes(Public)); var id=new byte[16]; Array.Copy(hash,id,16); return new Guid(id).ToString("N"); } } }
    }
    // Signed login proves possession of the device key. Profile IDs are public, not passwords.
    public static class CampIdentity
    {
        static CampKey key;
        static string storagePath;
        static bool ephemeralKey;
        public static string Session=>Key.Session;
        static CampKey Key
        {
            get
            {
                if(key!=null) return key;
                var args=Environment.GetCommandLineArgs(); int i=Array.IndexOf(args,"-identity-file");
                string path=i>=0 && i+1<args.Length ? args[i+1] : null;
                bool ephemeral=Array.IndexOf(args,"-smoke-test")>=0 || Array.IndexOf(args,"-items-smoke-test")>=0 || Array.IndexOf(args,"-camp-preview")>=0 || Array.IndexOf(args,"-skills-smoke")>=0;
                bool androidStorage=path==null && !ephemeral && Application.platform==RuntimePlatform.Android;
                if(androidStorage) path=AndroidKeyPath();
                storagePath=path; ephemeralKey=ephemeral && path==null;
                bool migrate=androidStorage && !File.Exists(path);
                string json=path!=null && File.Exists(path) ? File.ReadAllText(path) :
                    migrate || path==null && !ephemeral ? PlayerPrefs.GetString("camp_key_v2","") : "";
                if(!string.IsNullOrEmpty(json)) key=JsonUtility.FromJson<CampKey>(json);
                if(key==null || key.Parameters().Modulus.Length!=256)
                {
                    // Unity's Mono provider may retain the key initially generated by RSA.Create
                    // when only KeySize is reassigned. Construct at the intended size instead.
                    key=GenerateKey();
                    SaveKey(key);
                }
                else if(migrate) SaveKey(key);
                if(androidStorage && PlayerPrefs.HasKey("camp_key_v2"))
                { PlayerPrefs.DeleteKey("camp_key_v2"); PlayerPrefs.Save(); }
                return key;
            }
        }
        static CampKey GenerateKey()
        { using(var rsa=new RSACryptoServiceProvider(2048)) { rsa.PersistKeyInCsp=false; return CampKey.From(rsa.ExportParameters(true)); } }
        static string AndroidKeyPath()
        {
            using(var unity=new AndroidJavaClass("com.unity3d.player.UnityPlayer"))
            using(var activity=unity.GetStatic<AndroidJavaObject>("currentActivity"))
            using(var context=activity.Call<AndroidJavaObject>("getApplicationContext"))
            using(var folder=context.Call<AndroidJavaObject>("getNoBackupFilesDir"))
                return Path.Combine(folder.Call<string>("getAbsolutePath"),"camp-identity-v2.json");
        }
        static void SaveKey(CampKey value)
        {
            if(storagePath!=null)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(storagePath)));
                string temporary=storagePath+".tmp";
                File.WriteAllText(temporary,JsonUtility.ToJson(value));
                if(File.Exists(storagePath)) File.Replace(temporary,storagePath,null);
                else File.Move(temporary,storagePath);
            }
            else if(!ephemeralKey) { PlayerPrefs.SetString("camp_key_v2",JsonUtility.ToJson(value)); PlayerPrefs.Save(); }
        }
        // Chamada somente apos a confirmacao do jogador, sem apagar o perfil no servidor.
        public static void CreateSeparateProfile()
        {
            var previous=Key;
            string folder=storagePath!=null ? Path.GetDirectoryName(Path.GetFullPath(storagePath)) : Application.persistentDataPath;
            string archive=Path.Combine(folder,"identity-archive");
            Directory.CreateDirectory(archive);
            string backup=Path.Combine(archive,previous.Session+".json");
            if(!File.Exists(backup)) File.WriteAllText(backup,JsonUtility.ToJson(previous));
            var replacement=GenerateKey();
            SaveKey(replacement);
            key=replacement;
        }
        static byte[] Data(CampJoinRequest r)=>Encoding.UTF8.GetBytes(r.Session+"|"+r.IssuedTicks+"|"+r.Nonce+"|"+r.CampOnly+"|"+r.Map+"|"+r.QuickTest+"|"+r.QuickBots+"|"+r.CampSandbox+"|"+r.TestAccessProbe+
            (string.IsNullOrEmpty(r.DungeonContentHash) ? "" : "|"+r.DungeonContentHash));
        public static void Sign(CampJoinRequest r)
        {
            r.Session=Key.Session; r.PublicKey=Key.Public; r.IssuedTicks=DateTime.UtcNow.Ticks; r.Nonce=Guid.NewGuid().ToString("N");
            using(var rsa=RSA.Create()) { rsa.ImportParameters(Key.Parameters()); r.Signature=Convert.ToBase64String(rsa.SignData(Data(r),HashAlgorithmName.SHA256,RSASignaturePadding.Pkcs1)); }
        }
        public static bool Verify(CampJoinRequest r,long now)
        {
            try
            {
                if(r==null || r.PublicKey==null || r.PublicKey.Length>500 || r.Signature==null || r.Signature.Length>500 || !Guid.TryParseExact(r.Nonce,"N",out _) ||
                    r.IssuedTicks<now-TimeSpan.FromMinutes(2).Ticks || r.IssuedTicks>now+TimeSpan.FromSeconds(30).Ticks || r.Actions!=null && r.Actions.Length!=0 || r.RepairPier || r.Fish) return false;
                var parts=r.PublicKey.Split(':'); if(parts.Length!=2) return false;
                var k=new CampKey { Modulus=parts[0],Exponent=parts[1] };
                if(k.Session!=r.Session || k.Parameters().Modulus.Length!=256) return false;
                using(var rsa=RSA.Create()) { rsa.ImportParameters(k.Parameters()); return rsa.VerifyData(Data(r),Convert.FromBase64String(r.Signature),HashAlgorithmName.SHA256,RSASignaturePadding.Pkcs1); }
            }
            catch(ArgumentException) { return false; } catch(FormatException) { return false; } catch(CryptographicException) { return false; }
        }
    }
}
